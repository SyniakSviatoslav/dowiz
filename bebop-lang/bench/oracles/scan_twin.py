#!/usr/bin/env python3
"""scan_twin.py — B2 decisive twin (ii) oracle (docs/blueprints/B2-decisive-twins.md §3(ii)).
Fixed schema: 3 i64 columns (c0,c1,c2) generated by one LCG stream; predicate
c0 in [LO,HI) and c1 < Q; aggregate sum(c2). Same constants/generator as
bench/vs_rust/std_tests/gen_scan.py (the .bp template writer) and
bench/vs_rust/rust_once/scan_const.rs / scan_generic.rs.
CLI: python3 scan_twin.py <n>
"""
import sys

M64 = (1 << 64) - 1
A = 6364136223846793005
C = 1442695040888963407
LO, HI, Q = 200000, 500000, 500
SEED = 5591


def lcg(x):
    return (x * A + C) & M64


def scan(n, seed=SEED):
    x = seed
    s = 0
    for _ in range(n):
        x = lcg(x)
        c0 = (x >> 20) % 1000000
        x = lcg(x)
        c1 = (x >> 40) % 1000
        x = lcg(x)
        c2 = (x >> 10) % 1000000
        if LO <= c0 < HI and c1 < Q:
            s += c2
    return s


if __name__ == '__main__':
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 20000
    print('sum', scan(n))
